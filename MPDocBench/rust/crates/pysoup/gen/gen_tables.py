"""Generate src/generated.rs from the exact Python 3.11 / bs4 4.11.1 environment.

Run with the reference interpreter (the one that has bs4 4.11.1):
    python gen/gen_tables.py > src/generated.rs
"""
import sys
import unicodedata
from html.entities import html5
from bs4.dammit import EntitySubstitution

assert unicodedata.unidata_version == "14.0.0", unicodedata.unidata_version


def rs(s):
    return '"' + ''.join(
        c if (32 <= ord(c) < 127 and c not in '"\\') else '\\u{%x}' % ord(c)
        for c in s) + '"'


def ranges(pred):
    out = []
    start = None
    for c in range(0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_surrogate(c):
    return 0xD800 <= c <= 0xDFFF


w = sys.stdout.write
w("// @generated by gen/gen_tables.py from Python %s / bs4 html5 tables. Do not edit.\n\n"
  % sys.version.split()[0])

# html.entities.html5, sorted by name (keys include the variants with and without ';')
items = sorted(html5.items())
w("pub static HTML5: &[(&str, &str)] = &[\n")
for k, v in items:
    w("    (%s, %s),\n" % (rs(k), rs(v)))
w("];\n\n")

# bs4 EntitySubstitution.HTML_ENTITY_TO_CHARACTER
items = sorted(EntitySubstitution.HTML_ENTITY_TO_CHARACTER.items())
w("pub static BS4_ENTITY_TO_CHARACTER: &[(&str, &str)] = &[\n")
for k, v in items:
    w("    (%s, %s),\n" % (rs(k), rs(v)))
w("];\n\n")

# str.lower() for non-ASCII code points whose lowercase differs (context-free part)
w("pub static PY_LOWER: &[(char, &str)] = &[\n")
for c in range(0x80, 0x110000):
    if is_surrogate(c):
        continue
    ch = chr(c)
    lo = ch.lower()
    if lo != ch:
        w("    ('\\u{%x}', %s),\n" % (c, rs(lo)))
w("];\n\n")

# str.isalnum() (Python re \w is isalnum() or '_')
w("pub static PY_ALNUM_RANGES: &[(u32, u32)] = &[\n")
for a, b in ranges(lambda c: not is_surrogate(c) and chr(c).isalnum()):
    w("    (0x%x, 0x%x),\n" % (a, b))
w("];\n\n")

# Code points unassigned in Unicode 14 (Python leaves them untouched in NFKC)
w("pub static PY_UNASSIGNED_RANGES: &[(u32, u32)] = &[\n")
for a, b in ranges(lambda c: not is_surrogate(c) and unicodedata.category(chr(c)) == 'Cn'):
    w("    (0x%x, 0x%x),\n" % (a, b))
w("];\n\n")

# Unicode decimal digits (int() accepts them): (code point, value)
w("pub static PY_DECIMAL_RANGES: &[(u32, u32, u32)] = &[\n")
dec = [(c, unicodedata.decimal(chr(c))) for c in range(0x80, 0x110000)
       if not is_surrogate(c) and unicodedata.decimal(chr(c), None) is not None]
runs = []
for c, v in dec:
    if runs and runs[-1][1] + 1 == c and runs[-1][2] + (c - runs[-1][0]) == v:
        runs[-1][1] = c
    else:
        runs.append([c, c, v])
for a, b, v in runs:
    w("    (0x%x, 0x%x, %d),\n" % (a, b, v))
w("];\n")
